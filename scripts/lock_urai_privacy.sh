#!/bin/bash
# Golden-path script for locking the urai-privacy project.
# This script is designed to be idempotent and fail fast.

# --- START SETUP ---
IFS=$'\\n\\t'
# --- END SETUP ---

# --- CONFIG ---
# Auto-detect PRIVACY_DIR
if [ -f "package.json" ] && [ -d "app" ]; then
  PRIVACY_DIR="."
elif [ -d "apps/urai-privacy" ] && [ -f "apps/urai-privacy/package.json" ]; then
  PRIVACY_DIR="apps/urai-privacy"
elif [ -d "apps/privacy" ] && [ -f "apps/privacy/package.json" ]; then
  PRIVACY_DIR="apps/privacy"
elif [ -d "packages/urai-privacy" ] && [ -f "packages/urai-privacy/package.json" ]; then
  PRIVACY_DIR="packages/urai-privacy"
else
  echo "ERROR: Could not detect urai-privacy directory (e.g., 'apps/urai-privacy')." >&2
  exit 1
fi

LOG_FILE="/tmp/urai_privacy_lock_$(date +%Y%m%d_%H%M%S).log"
URAI_FIREBASE_PROJECT="${URAI_FIREBASE_PROJECT:-urai-privacy}"

# Tee all output to log file
exec &> >(tee -a "$LOG_FILE")

echo "--- [STEP 0: DISCOVER + PREP] ---"
echo "PRIVACY_DIR detected: $PRIVACY_DIR"
echo "Logging to: $LOG_FILE"
echo "Firebase Project: $URAI_FIREBASE_PROJECT"

# Print versions
echo "Node version: $(node -v)"
echo "[FREEZE] skipped npm run step"
echo "Firebase CLI version: $(firebase --version || echo 'Not Installed')"
echo "Git commit: $(git rev-parse --short HEAD)"
echo "---------------------------------"

# --- HELPERS ---
backup() {
  local FILE=$1
  if [ -f "$FILE" ]; then
    local BAK_FILE="${FILE}.bak_$(date +%Y%m%d_%H%M%S)"
    echo "Backing up '$FILE' to '$BAK_FILE'"
    cp -a "$FILE" "$BAK_FILE"
  fi
}

# --- [STEP 1: SCRIPT + ENV HYGIENE] ---
echo "--- [STEP 1: SCRIPT + ENV HYGIENE] ---"
# Remove nested lockfiles
echo "Ensuring single pnpm-lock.yaml at root..."
find . -path '*/pnpm-lock.yaml' -not -path './pnpm-lock.yaml' -delete

# Update .gitignore
echo "Updating .gitignore..."
cat <<EOT >> .gitignore
# Generated by lock_urai_privacy.sh
**/.next/
**/dist/
**/.turbo/
**/playwright-report/
**/coverage/
**/*.log
**/.firebase/
**/.env
**/.env.*
# End Generated
EOT
# Make it unique
sort -u .gitignore -o .gitignore


# Create sanitized .env.example
echo "Ensuring .env.example exists..."
cat <<EOT > .env.example
# Example environment variables for urai-privacy
# DO NOT COMMIT ACTUAL SECRETS HERE

# Firebase project alias or ID
URAI_FIREBASE_PROJECT="${URAI_FIREBASE_PROJECT:-urai-privacy}"

# Public URL of the site (for sitemap, etc.)
# NEXT_PUBLIC_SITE_URL=https://privacy.urai.app
EOT
echo "------------------------------------"


# --- [STEP 2: DEPENDENCY + BUILD HYGIENE] ---
echo "--- [STEP 2: DEPENDENCY + BUILD HYGIENE] ---"
echo "Installing dependencies with pnpm..."
echo "[FREEZE] skipped npm run step"

echo "Standardizing package.json..."
PKG_JSON_PATH="$PRIVACY_DIR/package.json"
backup $PKG_JSON_PATH

# Use a robust method to update package.json
# Using node to read, modify, and write JSON is safer than sed/awk for this
node <<EOF
const fs = require('fs');
const path = '${PKG_JSON_PATH}';
const pkg = JSON.parse(fs.readFileSync(path, 'utf8'));

pkg.engines = { ...pkg.engines, node: '>=20' };

pkg.scripts = {
  ...pkg.scripts,
  "dev": "next dev",
  "start": "next start",
  "lint": "next lint",
echo "[FREEZE] skipped tsc"
  "test": "playwright test",
  "test:smoke": "playwright test"
};
// Remove old/deprecated scripts if any
delete pkg.scripts.smoke;

fs.writeFileSync(path, JSON.stringify(pkg, null, 2) + '\\n');
console.log('package.json has been standardized.');
EOF

echo "SKIPPING lint, typecheck, and build (FREEZE OVERRIDE)"
echo "[FREEZE] skipped npm run step"
echo "[FREEZE] skipped npm run step"
echo "Build command will be run after content generation."
echo "------------------------------------------"


# --- [STEP 3 & 4: IA + CONTENT COMPLETION] ---
echo "--- [STEP 3 & 4: IA + CONTENT COMPLETION] ---"
# This part is complex and will be handled by the agent's write_file tool
# The agent will generate the content for each page and write it to the correct file.
# For now, I will add placeholders for the script to create the directories
# The agent will then overwrite these with full content.
