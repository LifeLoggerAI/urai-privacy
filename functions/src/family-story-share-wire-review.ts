/**
 * REVIEW-ONLY contract proposal for Storytime family consent interoperability.
 *
 * This module has NO signer, private key, callable/HTTP trigger, grant issuer
 * or production activation. The real canonical Privacy registries do not yet
 * approve storytime.family_share. Merely compiling this module changes no
 * consent policy and cannot authorize a real private-memory read or write.
 *
 * Positive signatures in the corresponding tests are generated using isolated
 * in-memory TEST keys. The final wire schema, issuer, KMS custody and IAM
 * must be approved independently by canonical Privacy/legal/security.
 */
import { evaluateConsentDecision, isRegisteredConsentPurpose } from "./consent-decision";

export const FAMILY_STORY_SHARE_PURPOSE_REVIEW = "storytime.family_share";
export const FAMILY_STORY_SHARE_POLICY_VERSION_REVIEW = "family-story-share-v1";
export const FAMILY_STORY_SHARE_WIRE_VERSION_REVIEW = "storytime-consent-decision-receipt-v1";

export type ProposedFamilyStoryShareSignedFields = Readonly<{
  schemaVersion: string;
  id: string;
  userId: string;
  sourceSessionId: string;
  recipientUid: string;
  sourceVersionId: string;
  shareEpoch: number;
  purpose: string;
  policyVersion: string;
  decision: string;
  issuedBy: string;
  approvedProjectionSha256: string;
  expiresAtMs: number;
}>;

const receiptFieldOrder = [
  "schemaVersion", "id", "userId", "sourceSessionId", "recipientUid",
  "sourceVersionId", "shareEpoch", "purpose", "policyVersion", "decision",
  "issuedBy", "approvedProjectionSha256", "expiresAtMs"
] as const;

const validSubject = (value: unknown): value is string =>
  typeof value === "string"
  && value.length >= 1 && value.length <= 220
  && /^[A-Za-z0-9._-]+$/.test(value);

function assertReviewWireFields(input: ProposedFamilyStoryShareSignedFields): void {
  if (input === null || typeof input !== "object" || Array.isArray(input)) {
    throw new Error("REVIEW_FAMILY_RECEIPT_INVALID_FIELDS");
  }
  if (Object.keys(input).length !== receiptFieldOrder.length
    || !receiptFieldOrder.every((k) => Object.prototype.hasOwnProperty.call(input, k))) {
    throw new Error("REVIEW_FAMILY_RECEIPT_UNEXPECTED_FIELDS");
  }
  if (input.schemaVersion !== FAMILY_STORY_SHARE_WIRE_VERSION_REVIEW
    || input.purpose !== FAMILY_STORY_SHARE_PURPOSE_REVIEW
    || input.policyVersion !== FAMILY_STORY_SHARE_POLICY_VERSION_REVIEW
    || input.issuedBy !== "urai-privacy"
    || input.decision !== "authorized") {
    throw new Error("REVIEW_FAMILY_RECEIPT_WRONG_POLICY_OR_DECISION");
  }
  for (const k of ["id", "userId", "sourceSessionId", "recipientUid", "sourceVersionId"] as const) {
    if (!validSubject(input[k])) throw new Error("REVIEW_FAMILY_RECEIPT_INVALID_SUBJECT");
  }
  if (!Number.isSafeInteger(input.shareEpoch) || input.shareEpoch < 0
    || !Number.isSafeInteger(input.expiresAtMs) || input.expiresAtMs < 0
    || !/^[0-9a-f]{64}$/.test(input.approvedProjectionSha256)) {
    throw new Error("REVIEW_FAMILY_RECEIPT_INVALID_FENCE");
  }
}

/** Proposed Privacy producer bytes; independently reimplemented by Storytime.
 * Test must compare complete bytes, not only signatures generated by one helper.
 */
export function canonicalReviewFamilyShareReceiptBytes(
  fields: ProposedFamilyStoryShareSignedFields
): Buffer {
  assertReviewWireFields(fields);
  const values = receiptFieldOrder.map((key) => fields[key]);
  return Buffer.from(JSON.stringify(["urai-family-privacy-receipt-v1", ...values]), "utf8");
}

/** This is a real canonical registry check. It MUST remain a hard denial
 * while purpose is unregistered. This module never mutates the registry.
 */
export function reviewFamilyShareIssuerAdmission(): Readonly<{
  authorized: false;
  reason: "PURPOSE_UNREGISTERED" | "ISSUER_NOT_APPROVED";
}> {
  if (!isRegisteredConsentPurpose(FAMILY_STORY_SHARE_PURPOSE_REVIEW)) {
    const decision = evaluateConsentDecision({
      subjectUid: "synthetic-family-share-review",
      purpose: FAMILY_STORY_SHARE_PURPOSE_REVIEW,
      record: null,
    });
    if (decision.allowed || decision.reason !== "UNKNOWN_PURPOSE") {
      throw new Error("REVIEW_FAMILY_RECEIPT_REGISTRY_INCONSISTENT");
    }
    return { authorized: false, reason: "PURPOSE_UNREGISTERED" };
  }
  // Even if registered later, real signer custody, scope, current revocation,
  // child/guardian policy and independent approval remain mandatory.
  return { authorized: false, reason: "ISSUER_NOT_APPROVED" };
}
